//. This file is used as both data url and SaveUrl
//. Generates data for FastGrid by get() function or saves received changes to database by set() function
//. Uses UTF8Store object from UTF8Store.js to create FastGrid JSON data with UTF8Store format
// -----------------------------------------------------------------------------------------------------------------------------
//. Reads data from database and returns them in JSON
function get(req,res){
var sql = require('better-sqlite3'), db = new sql('SQLite.db'); //. It uses SQLite3 database engine on database in file SQLite.sb
var UTF8Store = require("./UTF8Store.js");
try { var rows = db.prepare("SELECT * FROM TreeData ORDER BY (SELECT TRIM(pid || ' ' || id))").all(); } //. Selects the whole table and calls the process function with the results
catch(e){ err("SQL select error: "+e.message,res); return; } 

var s = "FGrid.Data={";
s += "Cfg:{IgnoreDVOnU:1},"; //. Ignores default V defined in default rows for rows with U attribute
s += "Body_Cfg:{Par:'P'},"; //. Assigns the defined par "P" for all rows in Body. The Body definition is now one strings, where every row consists of 11 characters (id = 3 chars, L = 1 char, U = 7 chars)
s += "Body:\"";
var F = "\",Foot:[";
var Ids = [], Products = []; Names = []; Amounts = [], Prices = [], Discounts = [], Shippings = [];
var uid = UTF8Store.AddToUCode(0xE4,1), uD = UTF8Store.GetUCode(1,0,0,1,9), uE = UTF8Store.GetUCode(2,0,2,100), uI = UTF8Store.AddToUCode(0x4,new Date(2005,7,1));
for(var i=0;i<rows.length;i++){ 
   var r = rows[i];
   if(r.pid=="#") F += "{id:\"" + r.id + "\",V:[,,,," + r.G + "]},";
   else {
      s += UTF8Store.WriteValue(r.id,uid,0,Ids,null,0);            //. id = 2 chars as adjacent string and number
      s += UTF8Store.WriteValue(r.pid==""?0:1,0x01,0,null,null,0); //. L = 1 char number
      s += UTF8Store.WriteValue(r.A,0x03,0,Products,null,0);       //. A = Product / Order name, 1 char, max. 63415 products
      s += UTF8Store.WriteValue(r.C,0x03,0,Names,null,0);          //. C = Customer, 1 char, max 63415 names. Codes names and surnames together as plain string, because the most names are empty
      s += UTF8Store.WriteValue(r.D||0,uD,0,Amounts,null,1);       //. D = Amount, 1 char, values bigger than 50k are saved to Amounts
      s += UTF8Store.WriteValue(r.E||0,uE,0,Prices,null,1);        //. E = Unit price, 2 chars with 2 decimal places, codes integer numbers smaller, max. 4e7
      s += UTF8Store.WriteValues([r.G||0,r.H||0],[0x8E,0x0A],64,Discounts,Shippings,17); //. Merges G+H in one char 
         //. G = Discount, 4 bits, max. 16 values. If there will be more different discounts, it should be tested if WriteValue returns null (set by param err=64) and for such case recode the data with different ucode, e.g. 0x01
         //. H = Shipping, 1 rest char merged with the Discount 4 bits. The null/NaN/""/0 will produce only one byte, mainly for zero shipping, as the mostly used value. For other numbers  it will produce two bytes and stores them in Shippings, up to 3959 values.
         //. Discount and Shipping are coded here to strings, because the most of the values are zero, so they can be merged to one byte, instead of two characters
         //. Setting option=17 (&16) means that the the first value (G) will save strings to Discounts, but the second value (H) will save strings to Shipping
      var I = r.I&&r.I.split("-");
      s += UTF8Store.WriteValue(r.I ? new Date(I[0]-0,I[1]-1,I[2]-0) : "",uI); //. I = Date, 1 char as Date only
      }
   }
s += F + "],Cols:["; //. Saves the unique strings generated by WriteValue for the A, C, G and H columns. Assigns the ucode and uindex for the columns to correct decoding.
s += "{id:\"A\",UIndex:0,UCode:0x03,Texts:\""+UTF8Store.GetTexts(Products)+"\"},";    //. 1 char
s += "{id:\"C\",UIndex:1,UCode:0x03,Texts:\""+UTF8Store.GetTexts(Names)+"\"},";       //. 1 char
s += "{id:\"D\",UIndex:2,UCode:"+uD+",Texts:\""+UTF8Store.GetTexts(Amounts)+"\"},";      //. 1 char
s += "{id:\"E\",UIndex:3,UCode:"+uE+"},";                         //. 1 char
s += "{id:\"G\",UIndex:5,UCode:0x8E,Texts:\""+UTF8Store.GetTexts(Discounts)+"\"},";   //. 0.7 char (4 bits)
s += "{id:\"H\",UIndex:5.7,UCode:0x0A,Texts:\""+UTF8Store.GetTexts(Shippings)+"\"},"; //. 0.3 char (rest bits)
s += "{id:\"I\",UIndex:6,UCode:"+uI+"}";                          //. 1 char
s += "],";
s += "Par:{P:[";   //. Defines one par named "P", it will be used the same for all rows. It will code the two row attributes id and U
s += "'id',{UCode:"+uid+",Texts:\""+UTF8Store.GetTexts(Ids)+"\"},"; //. id is coded with ucode 0xcd as adjacent string with number as two characters
s += "'L',0x01,";  //. L is coded with ucode 0x01 as one character. It would be better to code with 0xB as one bit, by there is no other value to merge with.
s += "'U',0x2007"; //. The cell values are coded in U in UTF8 Store. The U attribute is coded to Par as raw with ucode 0x2000 + 7 => summary of ucode sizes: [A] 1 char + [C] 1 char + [D] 1 char + [E] 2 chars + [G+H] 1 char, [I] 1 char
s += "]}}";  
end(s,res);
}
// -----------------------------------------------------------------------------------------------------------------------------
//. Saves changed data in JSON to database
function set(req,res){
var qstr = require('querystring'), body = ""; 
req.on('data',function(data){ body += data.toString(); });
req.on('end', function(){
   var D = qstr.parse(body).Data; if(!D) { err("Empty request",res); return; }
   D = JSON.parse(D); 
   if(!D ||!D.ChangedRows) { err("Request without ChangedRows",res); return; }
   D = D.ChangedRows;
   for(var di=0,S=[];di<D.length;di++){
      var R = D[di], V = R.V || {}, s;
      if(R.Remove) s = "DELETE FROM TreeData WHERE ID="+R.id;
      else if(R.Add==1){
         s = "INSERT INTO TreeData(id,pid,"; var sv = "'" + R.id + "','" + (R.Parent||"") + "',";
         if(R.V) for(var n in V) { s += n + ","; sv += n=="A"||n=="C"||n=="I" ? "'" + (V[n]+"").replace("'","''") + "'," : V[n] + ","; }
         s = s.slice(0,-1) + ") VALUES(" + sv.slice(0,-1) + ")"; //. Last commas away
         }
      else if(R.Parent||R.V){
         s = "UPDATE TreeData SET ";
         if(R.V) for(var n in V) s += n=="A"||n=="C"||n=="I" ? n + " = '" + (V[n]+"").replace("'","''") + "'," : n + " = " + V[n] + ",";
         if(R.Parent) s += "pid = '" + R.Parent.replace("'","''") + ".',";
         s = s.slice(0,-1) + " WHERE id='" + R.id + "'"; //. Last comma away
         }
      S.push(s);
      }
   console.log(S.join("\n"));
   try { 
      var sql = require('better-sqlite3'), db = new sql('SQLite.db'); //. It uses SQLite3 database engine on database in file SQLite.sb
      for(var i=0;i<S.length;i++) db.prepare(S[i]).run(); //. Runs the commands one by one, because SQLite cannot run more commands at once
      }
   catch(e){ err("SQL command error: "+e.message,res); return; }
   end("{IO:{Message:'Data saved successfully'}}",res);
   });
}
// -----------------------------------------------------------------------------------------------------------------------------
//. Support function,ends with str
function end(str,res){ 
res.writeHead(200, {"Content-Type":"text/plain; charset=utf-8","Access-Control-Allow-Origin":"*"}); //. Sets response header to UTF8 text and allows requests from other domains / ports
res.end(str);
}
// -----------------------------------------------------------------------------------------------------------------------------
//. Support function, logs given error and ends with JSON error
function err(e,res){ 
console.log("!"+e); 
end("{IO:{Result:\"-1\",Message:\""+e.replace(/"/g,"'")+"\"}}",res);
}
// -----------------------------------------------------------------------------------------------------------------------------
module.exports = { get, set };