<script>
import { FastGrid } from "fastgrid-svelte";
import "../Tutorial.css";

function onLoadError(G,source,code,message,index){
   return source.indexOf("getdef")>=0 ? { IO:{ Message:"Sample node server is not running on localhost:8000<br>You need to install and start node package in <b>./server/</b>" } } : {};
   }

let grid = null; //. Grid reference received for grid, access the grid object as grid
</script>

<h1>5. Grid from SQL server</h1>
   <h5>Generates grouped grid from plain table by dynamic layout script. Using SQLite database table on Node server.</h5>
   <ul>
      <li>
         Generates treetable from standard database table. Also flips the table and shows data in changed layout.
         For every action there is used another support code (Layout, Data, Upload). The layout is also generated.<br />
         Rows are identified by one unique editable column, with using full ids (including parents ids).
         For demonstration it shows id column, to see what ids are generated by FastGrid.<br />
      </li>
      <li>
         Sample Node server must be running on <b>http://localhost:8000</b>. The sample Node server package is located at <b>./server/</b>.<br/>
         The sample layout is loaded from <b><a href="http://localhost:8000/SQLGrid.js?func=getdef" target="_blank">http://localhost:8000/SQLGrid.js?func=getdef</a></b>, 
         the sample data are loaded from <b><a href="http://localhost:8000/SQLGrid.js?func=getdata" target="_blank">http://localhost:8000/SQLGrid.js?func=getdata</a></b>
         and changes are saved to url <b>http://localhost:8000/SQLGrid.js?func=set</b>.
         PDF is generated on url <b>http://localhost:8000/Pdf.js?func=getpdf</b>.<br/>
         The sample data on server are stored in <b>./server/sqlite.db</b> database file in table <b>TableData</b>
         and the script loading and saving data is located at <b>./server/SQLGrid.js</b>
      </li>
   </ul>
   <FastGrid
      src={[ 'http://localhost:8000/SQLGrid.js?func=getdef', 'http://localhost:8000/SQLGrid.js?func=getdata', { Cfg: { SaveUrl: 'http://localhost:8000/SQLGrid.js?func=set', PdfUrl:'http://localhost:8000/Pdf.js?func=getpdf' } } ]}
      bind:this={grid} {onLoadError} style="height:100%; min-height:500px; width:100%"
      />
