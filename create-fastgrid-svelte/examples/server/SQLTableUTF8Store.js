//. This file is used as both data url and SaveUrl
//. Generates data for FastGrid by get() function or saves received changes to database by set() function
//. Uses UTF8Store object from UTF8Store.js to create FastGrid JSON data with UTF8Store format
// -----------------------------------------------------------------------------------------------------------------------------
//. Reads data from database and returns them in JSON
function get(req,res){
var sql = require('better-sqlite3'), db = new sql('SQLite.db'); //. It uses SQLite3 database engine on database in file SQLite.sb
var UTF8Store = require("./UTF8Store.js");
try { var rows = db.prepare("SELECT * FROM TableData").all(); } //. Selects the whole table and calls the process function with the results
catch(e){ err("SQL select error: "+e.message,res); return; } 
var s = "FGrid.Data={";
s += "Par:{P:[";   //. Defines one par named "P", it will be used the same for all rows. It will code the two row attributes id and U
s +=  "'id',0x1,";  //. id is coded with ucode 0x1 in one char
s += "'U',0x2005"; //. The cell values are coded in U in UTF8 Store. The U attribute is coded to Par as raw with ucode 0x2000 + 5 => summary of ucode sizes: [0x3] 1 char + [0xC9] 2 chars + [0x1] 1 char + [0x1] 1 char
s +=  "]},";  
s +=  "Body_Cfg:{Par:'P'},"; //. Assigns the defined par "P" for all rows in Body. The Body definition is now one strings, where every row consists of 6 characters (id = 1 char, U = 5 chars)
s +=  "Body:\"";
var Projects = [], Names = [], Surnames = [];
for(var i=0;i<rows.length;i++){ //. Saves the rows, every row has 6 characters (id = 1 char, U = 5 chars)
   var r = rows[i];
   s += UTF8Store.WriteValue(r.ID,0x01,0,null,null,1)            //. id
      + UTF8Store.WriteValue(r.Project,0x03,0,Projects,null,0)   //. Project, 1 char
      + UTF8Store.WriteValue(r.Resource,0xCD,0,Names,Surnames,0) //. Resource, 2 chars
      + UTF8Store.WriteValue(r.Week,0x01,0,null,null,1)          //. Week, 1 char
      + UTF8Store.WriteValue(r.Hours,0x01,0,null,null,1);        //. Hours, 1 char
   }
s += "\",Cols:[" //. Saves the unique strings generated by WriteValue for the Project and Resource columns. Assigns the ucode and uindex for the columns to correct decoding.
   + "{id:\"Project\",UIndex:0,UCode:0x03,Texts:\""+UTF8Store.GetTexts(Projects)+"\"},"
   + "{id:\"Resource\",UIndex:1,UCode:0xCD,Texts:\""+UTF8Store.GetTexts(Names)+"\",UTexts:\""+UTF8Store.GetTexts(Surnames)+"\"},"
   + "{id:\"Week\",UIndex:3,UCode:0x01},"
   + "{id:\"Hours\",UIndex:4,UCode:0x01},"
   + "]}";
end(s,res);
}
// -----------------------------------------------------------------------------------------------------------------------------
//. Saves changed data in JSON to database
function set(req,res){
var qstr = require('querystring'), body = ""; 
req.on('data',function(data){ body += data.toString(); });
req.on('end', function(){
   var D = qstr.parse(body).Data; if(!D) { err("Empty request",res); return; }
   D = JSON.parse(D); 
   if(!D ||!D.ChangedRows) { err("Request without ChangedRows",res); return; }
   D = D.ChangedRows;
   for(var di=0,S=[];di<D.length;di++){
      var R = D[di], V = R.V || {}, s;
      if(R.Remove){
         s = "DELETE FROM TableData WHERE ID="+R.id+"\n";
         }
      else if(R.Add==1){
         s = "INSERT INTO TableData(ID,Project,Resource,Week,Hours) VALUES("
               + R.id + "," 
               + "'" + (V.Project ? (V.Project+"").replace("'","''") : '') + "',"
               + "'" + (V.Resource ? (V.Resource+"").replace("'","''") : '') + "',"
               + (V.Week ? V.Week : '0') + ","
               + (V.Hours ? V.Hours : '0') + ")\n";
         }
      else if(R.V){
         s = "UPDATE TableData SET ";
         for(var name in V){
            if(name=="Project" || name=="Resource") s += name+" = '" + (V[name]+"").replace("'","''") + "',";
            else if(name=="Week" || name=="Hours") s += name+" = " + V[name] + ",";
            }
         s = s.slice(0,-1) + " WHERE ID="+R.id+"\n";
         }
      S.push(s);
      }
   try { 
      var sql = require('better-sqlite3'), db = new sql('SQLite.db'); //. It uses SQLite3 database engine on database in file SQLite.sb
      for(var i=0;i<S.length;i++) db.prepare(S[i]).run(); //. Runs the commands one by one, because SQLite cannot run more commands at once
      }
   catch(e){ err("SQL command error: "+e.message,res); return; }
   end("{IO:{Message:'Data saved successfully'}}",res);
   });
}
// -----------------------------------------------------------------------------------------------------------------------------
//. Support function,ends with str
function end(str,res){ 
res.writeHead(200, {"Content-Type":"text/plain; charset=utf-8","Access-Control-Allow-Origin":"*"}); //. Sets response header to UTF8 text and allows requests from other domains / ports
res.end(str);
}
// -----------------------------------------------------------------------------------------------------------------------------
//. Support function, logs given error and ends with JSON error
function err(e,res){ 
console.log("!"+e); 
end("{IO:{Result:\"-1\",Message:\""+e.replace(/"/g,"'")+"\"}}",res);
}
// -----------------------------------------------------------------------------------------------------------------------------
module.exports = { get, set };